#!/usr/bin/env python3
"""Summarise benchmark runs as an AsciiDoc table (for doc/performance.adoc).

    report.py RUN_DIR... [--title TITLE] [--output FILE]

One row per run: scenario, load, throughput, latency quantiles (if
measured), server CPU cost per message, peak RSS, spread across repeats and
validity. The environment of the first run is printed above the table.
"""

import argparse
import json
import pathlib
import sys


def fmt(value, scale=1.0, digits=1, suffix=""):
    if value is None:
        return "-"
    return f"{value / scale:,.{digits}f}{suffix}"


def row(s: dict) -> str:
    f, lg = s["figures"], s["scenario"]["loadgen"]
    load = (f"{lg['type']} {lg['payload']}, {lg['connections']} conn × {lg['threads']} thr, "
            + ("closed loop" if not lg["rate"] else f"{lg['rate']:,} msg/s"))
    status = "ok" if s["valid"] and s["clean"] else "*not clean/valid*"
    cells = [
        s["scenario"]["name"],
        load,
        fmt(f["throughput.messages_per_s"], 1e6, 2, " M"),
        fmt(f["throughput.bytes_per_s"], 1e6, 0, " MB"),
        fmt(f.get("latency_ns.p50"), 1e3, 1, " µs"),
        fmt(f.get("latency_ns.p99"), 1e3, 1, " µs"),
        fmt(f.get("latency_ns.p999"), 1e3, 1, " µs"),
        fmt(f.get("server.ns_per_message"), 1, 0, " ns"),
        fmt(f.get("server.max_rss_kib"), 1024, 0, " MiB"),
        fmt(s["spread"].get("throughput.messages_per_s", 0) * 100, 1, 1, " %"),
        str(len(s["repeats"])),
        status,
    ]
    return "| " + " | ".join(cells)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("runs", nargs="+")
    ap.add_argument("--title", default="Benchmark results")
    ap.add_argument("--output")
    args = ap.parse_args()

    summaries = [json.loads((pathlib.Path(r) / "summary.json").read_text()) for r in args.runs]
    env = summaries[0]["env"]
    lines = [
        "// Generated by tools/bench/report.py. Do not edit; re-run it on new results.",
        "",
        f"Host: {env['cpu']}, kernel {env['kernel']}, revision `{env['revision'] or 'uncommitted'}`"
        + (" (dirty tree)" if env["dirty"] else "") + f", target `{summaries[0]['target']}`.",
        "",
        f".{args.title}",
        '[cols="2,4,2,2,1,1,1,2,1,1,1,1",options="header"]',
        "|===",
        "| Scenario | Load | Msg/s | Bytes/s | p50 | p99 | p99.9 | Server CPU/msg | Peak RSS | Spread | Runs | Status",
        *(row(s) for s in summaries),
        "|===",
        "",
    ]
    text = "\n".join(lines)
    if args.output:
        pathlib.Path(args.output).write_text(text)
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
