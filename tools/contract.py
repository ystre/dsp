#!/usr/bin/env python3
"""Metrics contract tool (contract/metrics.toml).

    contract.py names   [--component server|loadgen] [--phase1]
        Print the metric family names, one per line, with the prefix applied.

    contract.py check   --component server|loadgen <exposition-file|->
        Check a Prometheus text exposition against the contract:
          * every exported family must be in the contract (no undocumented metric);
          * every family marked `phase1 = true` must be exported, with the
            contract's labels (histograms: on the _bucket series, plus `le`).

    contract.py adoc
        Print the contract as AsciiDoc tables (doc/generated/metrics.adoc).
"""

import argparse
import pathlib
import re
import sys
import tomllib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import project  # noqa: E402

CONTRACT = project.ROOT / "contract" / "metrics.toml"


def load(component: str | None = None) -> list[dict]:
    data = tomllib.loads(CONTRACT.read_text())
    prefix = project.metric_prefix()
    out = []
    for comp in ("server", "loadgen"):
        if component and comp != component:
            continue
        for m in data.get(comp, []):
            m = dict(m)
            m["name"] = m["name"].replace("{prefix}", prefix)
            m["component"] = comp
            out.append(m)
    return out


SAMPLE = re.compile(r'^([a-zA-Z_:][a-zA-Z0-9_:]*)(?:\{(.*)\})?\s+\S+')
LABEL = re.compile(r'([a-zA-Z_][a-zA-Z0-9_]*)="(?:[^"\\]|\\.)*"')


def parse_exposition(text: str) -> dict[str, set[frozenset[str]]]:
    """Family name -> set of label-name sets seen on its samples."""
    families: dict[str, set[frozenset[str]]] = {}
    typed: dict[str, str] = {}
    for line in text.splitlines():
        if line.startswith("# TYPE "):
            _, _, name, kind = line.split(maxsplit=3)
            typed[name] = kind
            continue
        if not line or line.startswith("#"):
            continue
        m = SAMPLE.match(line)
        if not m:
            raise ValueError(f"unparseable sample: {line!r}")
        name, labels = m.group(1), m.group(2) or ""
        family = name
        for suffix in ("_bucket", "_sum", "_count"):
            base = name.removesuffix(suffix)
            if name.endswith(suffix) and typed.get(base) == "histogram":
                family = base
                break
        families.setdefault(family, set()).add(frozenset(LABEL.findall(labels)))
    return families


def check(component: str, text: str) -> list[str]:
    contract = {m["name"]: m for m in load(component)}
    exported = parse_exposition(text)
    problems = []
    for name, labelsets in sorted(exported.items()):
        if name not in contract:
            problems.append(f"{name}: exported but not in the contract")
            continue
        want = set(contract[name]["labels"])
        if contract[name]["type"] == "histogram":
            want_bucket = want | {"le"}
            if not any(ls in (frozenset(want), frozenset(want_bucket)) for ls in labelsets):
                problems.append(f"{name}: labels {sorted(map(sorted, labelsets))} != contract {sorted(want)}")
        elif any(set(ls) != want for ls in labelsets):
            problems.append(f"{name}: labels {sorted(map(sorted, labelsets))} != contract {sorted(want)}")
    for name, m in sorted(contract.items()):
        if m.get("phase1") and name not in exported:
            problems.append(f"{name}: in the contract (phase1) but not exported")
    return problems


def adoc() -> str:
    lines = [
        "// Generated by tools/contract.py adoc from contract/metrics.toml. Do not edit.",
        "",
    ]
    for component, title in (("server", "Server"), ("loadgen", "Load generator")):
        lines += [
            f".{title} metrics",
            '[cols="3m,1,2m,1,5",options="header"]',
            "|===",
            "| Name | Type | Labels | Phase 1 | Meaning",
        ]
        group = None
        for m in load(component):
            if m["group"] != group:
                group = m["group"]
                lines.append(f"5+h| {group}")
            labels = ", ".join(m["labels"]) or "-"
            meaning = m["help"].replace("|", "\\|")   # '|' separates AsciiDoc cells
            lines.append(f"| {m['name']} | {m['type']} | {labels} | {'yes' if m['phase1'] else ''} | {meaning}")
        lines += ["|===", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p_names = sub.add_parser("names")
    p_names.add_argument("--component", choices=("server", "loadgen"))
    p_names.add_argument("--phase1", action="store_true")
    p_check = sub.add_parser("check")
    p_check.add_argument("--component", choices=("server", "loadgen"), required=True)
    p_check.add_argument("file")
    sub.add_parser("adoc")
    args = ap.parse_args()

    if args.cmd == "names":
        for m in load(args.component):
            if not args.phase1 or m["phase1"]:
                print(m["name"])
    elif args.cmd == "check":
        text = sys.stdin.read() if args.file == "-" else pathlib.Path(args.file).read_text()
        problems = check(args.component, text)
        for p in problems:
            print(f"contract: {p}", file=sys.stderr)
        if problems:
            return 1
        print(f"contract: {args.component} exposition conforms ({len(parse_exposition(text))} families)")
    elif args.cmd == "adoc":
        print(adoc())
    return 0


if __name__ == "__main__":
    sys.exit(main())
